import { execSync } from 'node:child_process';
import { readFileSync, mkdirSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import path from 'node:path';

const version = process.argv[2] || JSON.parse(readFileSync('package.json', 'utf8')).version;
const pkgName = 'db-sync-desktop-client';
const arch = 'x86_64';
const pkgFileName = `${pkgName}-${version}-${arch}.pkg.tar.zst`;

console.log(`Building Arch Linux package: ${pkgFileName}...`);

const stageDir = path.resolve(`.pkg_stage_${Date.now()}`);
if (existsSync(stageDir)) rmSync(stageDir, { recursive: true, force: true });

mkdirSync(path.join(stageDir, 'usr/bin'), { recursive: true });
mkdirSync(path.join(stageDir, 'usr/share/applications'), { recursive: true });
mkdirSync(path.join(stageDir, 'usr/share/icons/hicolor/128x128/apps'), { recursive: true });
mkdirSync(path.join(stageDir, 'usr/share/icons/hicolor/32x32/apps'), { recursive: true });

// Copy binary
execSync(`cp "src-tauri/target/release/db-sync-desktop-client" "${stageDir}/usr/bin/db-sync-desktop-client"`);
execSync(`chmod 755 "${stageDir}/usr/bin/db-sync-desktop-client"`);

// Create desktop file
const desktopContent = `[Desktop Entry]
Name=DB-Sync Client
Comment=DB-Sync Client (PMA to Local MySQL)
Exec=db-sync-desktop-client
Icon=db-sync-desktop-client
Terminal=false
Type=Application
Categories=Development;Database;Utility;
`;
writeFileSync(path.join(stageDir, 'usr/share/applications/db-sync-desktop-client.desktop'), desktopContent);

// Copy icons
if (existsSync('src-tauri/icons/128x128.png')) {
  execSync(`cp "src-tauri/icons/128x128.png" "${stageDir}/usr/share/icons/hicolor/128x128/apps/db-sync-desktop-client.png"`);
}
if (existsSync('src-tauri/icons/32x32.png')) {
  execSync(`cp "src-tauri/icons/32x32.png" "${stageDir}/usr/share/icons/hicolor/32x32/apps/db-sync-desktop-client.png"`);
}

// Calculate size
const binarySize = readFileSync(path.join(stageDir, 'usr/bin/db-sync-desktop-client')).length;

// Create .PKGINFO
const pkgInfoContent = `# Generated by create-arch-pkg
pkgname = ${pkgName}
pkgbase = ${pkgName}
pkgver = ${version}-1
pkgdesc = DB-Sync Client (PMA to Local MySQL)
url = https://github.com/HeriEfendi/DB-Sync-Desktop-Client
builddate = ${Math.floor(Date.now() / 1000)}
packager = Release Bot <noreply@github.com>
size = ${binarySize}
arch = ${arch}
license = MIT
depend = webkit2gtk-4.1
depend = gtk3
depend = cairo
depend = hicolor-icon-theme
depend = openssl
provides = ${pkgName}
conflicts = ${pkgName}
`;
writeFileSync(path.join(stageDir, '.PKGINFO'), pkgInfoContent);

// Create tar.zst
execSync(`tar -c --owner=root --group=root -C "${stageDir}" .PKGINFO usr | zstd -3 -o "${pkgFileName}"`, { stdio: 'inherit' });

// Cleanup
rmSync(stageDir, { recursive: true, force: true });

console.log(`Successfully created Arch Linux package: ${pkgFileName}`);
